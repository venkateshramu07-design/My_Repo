package com.batchmates.app.data.firebase

import android.content.Context
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import com.batchmates.app.data.AppUser
import com.batchmates.app.data.AuthRepository
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.FirebaseUser
import com.google.firebase.auth.GoogleAuthProvider
import com.google.firebase.auth.userProfileChangeRequest
import com.google.firebase.firestore.FieldValue
import com.google.firebase.firestore.FirebaseFirestore
import com.google.firebase.firestore.SetOptions
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.tasks.await

class FirebaseAuthRepository(appContext: Context) : AuthRepository {

    private val auth = FirebaseAuth.getInstance()
    private val db = FirebaseFirestore.getInstance()
    private val _user = MutableStateFlow(auth.currentUser?.toAppUser())
    override val currentUser: StateFlow<AppUser?> = _user

    /** Generated by the google-services plugin from google-services.json (needs Google sign-in enabled). */
    private val webClientId: String? = appContext.resources
        .getIdentifier("default_web_client_id", "string", appContext.packageName)
        .takeIf { it != 0 }
        ?.let { appContext.getString(it) }

    override val googleAvailable: Boolean get() = webClientId != null

    init {
        auth.addAuthStateListener { _user.value = it.currentUser?.toAppUser() }
    }

    override suspend fun signInWithGoogle(activityContext: Context): Result<AppUser> = runCatching {
        val clientId = requireNotNull(webClientId) { "Enable Google sign-in in Firebase and re-download google-services.json" }
        val option = GetSignInWithGoogleOption.Builder(clientId).build()
        val request = GetCredentialRequest.Builder().addCredentialOption(option).build()
        val credential = CredentialManager.create(activityContext).getCredential(activityContext, request).credential
        check(credential is CustomCredential && credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
            "Unexpected credential type"
        }
        val idToken = GoogleIdTokenCredential.createFrom(credential.data).idToken
        val user = auth.signInWithCredential(GoogleAuthProvider.getCredential(idToken, null)).await().user!!
        user.toAppUser().also { saveProfile(it) }
    }

    override suspend fun signInWithEmail(email: String, password: String): Result<AppUser> = runCatching {
        auth.signInWithEmailAndPassword(email.trim(), password).await().user!!.toAppUser()
    }

    override suspend fun signUpWithEmail(name: String, email: String, password: String): Result<AppUser> = runCatching {
        val user = auth.createUserWithEmailAndPassword(email.trim(), password).await().user!!
        user.updateProfile(userProfileChangeRequest { displayName = name.trim() }).await()
        user.reload().await()
        val appUser = (auth.currentUser ?: user).toAppUser().copy(name = name.trim())
        _user.value = appUser
        saveProfile(appUser)
        appUser
    }

    override suspend fun sendPasswordReset(email: String): Result<Unit> = runCatching {
        auth.sendPasswordResetEmail(email.trim()).await()
        Unit
    }

    override suspend fun signOut() {
        auth.signOut()
    }

    private suspend fun saveProfile(user: AppUser) {
        runCatching {
            db.collection("users").document(user.uid).set(
                mapOf(
                    "name" to user.name,
                    "photoUrl" to user.photoUrl,
                    "updatedAt" to FieldValue.serverTimestamp(),
                ),
                SetOptions.merge(),
            ).await()
        }
    }
}

internal fun FirebaseUser.toAppUser() = AppUser(
    uid = uid,
    name = displayName?.takeIf { it.isNotBlank() } ?: email?.substringBefore('@') ?: "Friend",
    email = email.orEmpty(),
    photoUrl = photoUrl?.toString(),
)
